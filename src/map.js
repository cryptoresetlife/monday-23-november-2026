const MAP = { w: 360, h: 172, lon0: -170, lon1: 190, lat0: 78, lat1: -50 };
const px = (lon) => ((lon - MAP.lon0) / (MAP.lon1 - MAP.lon0)) * MAP.w;
const py = (lat) => ((MAP.lat0 - lat) / (MAP.lat0 - MAP.lat1)) * MAP.h;

function drawMap(stories) {
  let s = `<svg id="map" viewBox="0 0 ${MAP.w} ${MAP.h}" xmlns="http://www.w3.org/2000/svg">`;
  for (const poly of LAND) {
    s += `<polygon points="${poly.map(([lo, la]) => `${px(lo).toFixed(1)},${py(la).toFixed(1)}`).join(' ')}" fill="#efe6d2" stroke="#9c907b" stroke-width=".6"/>`;
  }
  // nudge pins apart so close neighbours stay readable
  const placed = [];
  for (const st of stories) {
    let x = px(st.lon), y = py(st.lat);
    for (let k = 0; k < 12; k++) {
      const hit = placed.find((p) => Math.hypot(p.x - x, p.y - y) < 10.5);
      if (!hit) break;
      const a = (st.n * 2.4 + k) % (2 * Math.PI);
      x += Math.cos(a) * 6; y += Math.sin(a) * 6;
    }
    placed.push({ x, y });
    if (Math.hypot(x - px(st.lon), y - py(st.lat)) > 2) {
      s += `<line x1="${px(st.lon).toFixed(1)}" y1="${py(st.lat).toFixed(1)}" x2="${x.toFixed(1)}" y2="${y.toFixed(1)}" stroke="#555" stroke-width=".5"/>`;
    }
    s += `<circle cx="${x.toFixed(1)}" cy="${y.toFixed(1)}" r="5.4" fill="${COLORS[st.region]}" stroke="#fff" stroke-width=".8"/>`;
    s += `<text x="${x.toFixed(1)}" y="${(y + 2.4).toFixed(1)}" font-size="6.6" font-weight="700" fill="#fff" text-anchor="middle" font-family="Segoe UI,Arial">${st.n}</text>`;
  }
  return s + '</svg>';
}
